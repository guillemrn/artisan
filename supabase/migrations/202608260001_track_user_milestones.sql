create or replace view public.user_activation_funnel
with (security_invoker = true)
as
select
  user_id,
  min(occurred_at) filter (where event_name = 'user_confirmed') as confirmed_at,
  min(occurred_at) filter (where event_name = 'first_product_created') as first_product_at,
  min(occurred_at) filter (where event_name = 'first_sale_created') as first_sale_at,
  round(
    extract(epoch from (
      min(occurred_at) filter (where event_name = 'first_product_created')
      - min(occurred_at) filter (where event_name = 'user_confirmed')
    )) / 3600,
    1
  ) as hours_to_first_product,
  round(
    extract(epoch from (
      min(occurred_at) filter (where event_name = 'first_sale_created')
      - min(occurred_at) filter (where event_name = 'user_confirmed')
    )) / 3600,
    1
  ) as hours_to_first_sale,
  coalesce(
    min(occurred_at) filter (where event_name = 'first_sale_created')
      <= min(occurred_at) filter (where event_name = 'user_confirmed') + interval '7 days',
    false
  ) as aha_within_7_days
from public.user_milestones
group by user_id;

revoke all on public.user_activation_funnel from anon, authenticated;
