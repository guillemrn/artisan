-- Track the lifecycle steps that show whether a user reached Artisan's core value.
-- Milestone capture must never block signup, product creation, or sales.

create table if not exists public.user_milestones (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_name text not null check (
    event_name in ('user_confirmed', 'first_product_created', 'first_sale_created')
  ),
  occurred_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  notification_status text not null default 'pending' check (
    notification_status in ('pending', 'processing', 'sent', 'skipped', 'failed')
  ),
  notified_at timestamptz,
  resend_email_id text,
  notification_error text,
  unique (user_id, event_name)
);

create index if not exists user_milestones_event_occurred_idx
  on public.user_milestones (event_name, occurred_at desc);

alter table public.user_milestones enable row level security;
alter table public.user_milestones force row level security;

revoke all on table public.user_milestones from anon, authenticated;
revoke all on sequence public.user_milestones_id_seq from anon, authenticated;

create or replace function public.capture_user_milestone(
  p_user_id uuid,
  p_event_name text,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_user_id is null then
    return;
  end if;

  insert into public.user_milestones (user_id, event_name, metadata)
  values (p_user_id, p_event_name, coalesce(p_metadata, '{}'::jsonb))
  on conflict (user_id, event_name) do nothing;
exception
  when others then
    -- Analytics and notifications must not break the user's main operation.
    raise warning 'Could not capture milestone % for user %: %', p_event_name, p_user_id, sqlerrm;
end;
$$;

revoke all on function public.capture_user_milestone(uuid, text, jsonb) from public;

create or replace function public.capture_confirmed_user_milestone()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_should_capture boolean := false;
begin
  if tg_op = 'INSERT' then
    v_should_capture := new.email_confirmed_at is not null;
  elsif tg_op = 'UPDATE' then
    v_should_capture := new.email_confirmed_at is not null and old.email_confirmed_at is null;
  end if;

  if v_should_capture then
    perform public.capture_user_milestone(
      new.id,
      'user_confirmed',
      jsonb_strip_nulls(jsonb_build_object(
        'email', new.email,
        'full_name', new.raw_user_meta_data ->> 'full_name',
        'business_name', new.raw_user_meta_data ->> 'business_name',
        'business_type', new.raw_user_meta_data ->> 'business_type',
        'signup_at', new.created_at,
        'confirmed_at', new.email_confirmed_at
      ))
    );
  end if;

  return new;
end;
$$;

revoke all on function public.capture_confirmed_user_milestone() from public;

drop trigger if exists capture_confirmed_user_on_insert on auth.users;
create trigger capture_confirmed_user_on_insert
  after insert on auth.users
  for each row
  execute function public.capture_confirmed_user_milestone();

drop trigger if exists capture_confirmed_user_on_update on auth.users;
create trigger capture_confirmed_user_on_update
  after update of email_confirmed_at on auth.users
  for each row
  execute function public.capture_confirmed_user_milestone();

create or replace function public.capture_first_product_milestone()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text;
  v_user_metadata jsonb;
  v_user_created_at timestamptz;
  v_email_confirmed_at timestamptz;
begin
  select email, raw_user_meta_data, created_at, email_confirmed_at
    into v_email, v_user_metadata, v_user_created_at, v_email_confirmed_at
  from auth.users
  where id = new.user_id;

  perform public.capture_user_milestone(
    new.user_id,
    'first_product_created',
    jsonb_strip_nulls(jsonb_build_object(
      'email', v_email,
      'full_name', v_user_metadata ->> 'full_name',
      'business_name', v_user_metadata ->> 'business_name',
      'signup_at', v_user_created_at,
      'confirmed_at', v_email_confirmed_at,
      'product_id', new.id,
      'product_name', new.name
    ))
  );

  return new;
exception
  when others then
    raise warning 'Could not capture first product milestone for user %: %', new.user_id, sqlerrm;
    return new;
end;
$$;

revoke all on function public.capture_first_product_milestone() from public;

drop trigger if exists capture_first_product_after_insert on public.products;
create trigger capture_first_product_after_insert
  after insert on public.products
  for each row
  execute function public.capture_first_product_milestone();

